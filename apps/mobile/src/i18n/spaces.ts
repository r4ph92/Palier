// Keep a figure with its unit (« 9,75 $ », « 18 h 02 ») on one line.
export const NO_BREAK_SPACE = '\u00A0';
// Between the items of a list on one line (« ABC 123 · QC »); the dot never starts a line.
export const LIST_SEPARATOR = `${NO_BREAK_SPACE}· `;
// French thousands separator (« 1 234,56 $ »).
export const NARROW_NO_BREAK_SPACE = '\u202F';
